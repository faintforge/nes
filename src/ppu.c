Ppu ppu_init(MemoryBus bus) {
    Ppu ppu = {
        .bus = bus,
        .scanline = -1,
        .ppu_address_delay = -1,
    };

    memcpy(&ppu.palette, DEFAULT_PALETTE, sizeof(DEFAULT_PALETTE));
    ppu.palette_has_emph = true;

    ppu_ctrl(&ppu, 0x00);
    ppu_mask(&ppu, 0x00);
    ppu_oam_address(&ppu, 0x00);
    ppu_scroll(&ppu, 0x00);
    ppu_scroll(&ppu, 0x00);
    ppu_address(&ppu, 0x00);
    ppu_address(&ppu, 0x00);

    return ppu;
}

static void ppu__inc_hori(Ppu* ppu) {
    // Stolen from: www.nesdev.org/wiki/PPU_scrolling#Wrapping_around

    // Coarse-X is at end of nametable
    if ((ppu->v & 0x1F) == 31) {
        ppu->v &= ~0x1F; // Reset coarse-X
        ppu->v ^= 0x400; // Flip bit 10 responsible for horizontal nametable
                         // index.
    } else {
        ppu->v++;
    }
}

static void ppu__inc_vert(Ppu* ppu) {
    // Stolen from: www.nesdev.org/wiki/PPU_scrolling#Wrapping_around

    if (get_bits(ppu->v, 12, 14) < 7) {
        ppu->v += 0x1000;
    } else {
        // Clear fine-Y
        ppu->v = clear_bits(ppu->v, 12, 14);

        // Get coarse-Y
        u16 y = get_bits(ppu->v, 5, 9);
        if (y == 29) {
            y = 0;
            // Switch vertical nametable
            ppu->v ^= 0x8000;
        } else if (y == 31) {
            y = 0;
        } else {
            y++;
        }

        // Update coarse-Y
        ppu->v = clear_bits(ppu->v, 5, 9);
        ppu->v |= y << 5;
    }
}

static void ppu__shifter_push8(Ppu* ppu) {
    u8 pattern_plane0 = ppu->pattern_bus_low;
    u8 pattern_plane1 = ppu->pattern_bus_high;
    u8 coarse_x = get_bits(ppu->v, 0, 4);
    u8 coarse_y = get_bits(ppu->v, 5, 9);
    u8 quadrant_x = (coarse_x / 2) & 0x1;
    u8 quadrant_y = (coarse_y / 2) & 0x1;

    // yx yx yx yx
    // 11 10 01 00
    // BR BL TR TL
    u8 attribute = (ppu->at_bus >> 2*(quadrant_x | quadrant_y*2)) & 0x3;
    u8 palette = attribute;

    for (u8 dx = 0; dx < 8; dx++) {
        u8 palette_entry = get_bit(pattern_plane0, 7-dx) | (get_bit(pattern_plane1, 7-dx) << 1);
        u8 palette_index = palette*4 + palette_entry;
        assert(palette_index <= 0xF);

        u8 color = *ppu_get_color_ptr(ppu, palette_index);
        if (palette_entry == 0) {
            color = *ppu_get_bg_color_ptr(ppu);
        }

        ppu->shifter[8+dx] = color;
        ppu->shifter_palette_entries[8+dx] = palette_entry;
    }
}

static void ppu__shifter_pull(Ppu* ppu) {
    ppu->last_shifted = ppu->shifter[ppu->fine_x];
    ppu->last_shifted_palette_entry = ppu->shifter_palette_entries[ppu->fine_x];
    // Shift left
    memmove(ppu->shifter, ppu->shifter+1, 15*sizeof(*ppu->shifter));
    memmove(ppu->shifter_palette_entries, ppu->shifter_palette_entries+1, 15*sizeof(*ppu->shifter_palette_entries));
    ppu->shifter[15] = 0;
    ppu->shifter_palette_entries[15] = 0;
}

static void ppu__fetch_tile_data(Ppu* ppu, u32 starting_dot) {
    ppu__shifter_pull(ppu);

    // 1. Fetch nametable
    // 2. Fetch attribute table
    // 3. Pattern table tile low
    // 4. Pattern table tile high

    // Pattern address
    // https://www.nesdev.org/wiki/PPU_pattern_tables
    // 0HNNNN NNNNPyyy
    // Fine-Y
    u16 pattern_addr_plane0 = get_bits(ppu->v, 12, 14);
    pattern_addr_plane0 |= ppu->nt_bus << 4;
    pattern_addr_plane0 |= ppu->background_pattern_address;

    u8 t = (ppu->dot - starting_dot) & 0x7;
    if ((t & 1) == 0) {
        u16 v = ppu->v;
        u16 addresses[4] = {
            // NT
            0x2000 | (v & 0x0FFF),
            // AT
            0x23C0 | (v & 0x0C00) | ((v >> 4) & 0x38) | ((v >> 2) & 0x07),
            // Pattern low
            pattern_addr_plane0,
            // Pattern high
            pattern_addr_plane0 ^ 0x8, // Filp plane bit (bit 3)
        };
        ppu->address_bus = addresses[t >> 1];
    } else {
        u8* buses[4] = {
            &ppu->nt_bus,
            &ppu->at_bus,
            &ppu->pattern_bus_low,
            &ppu->pattern_bus_high,
        };
        *buses[t / 2] = ppu->bus.read(&ppu->bus, ppu->address_bus);
    }

    if (t == 7) {
        ppu__shifter_push8(ppu);
        ppu__inc_hori(ppu);
    }
}

static void ppu__scanline(Ppu* ppu) {
    // Idle cycle
    if (ppu->dot == 0) {
    } else if (ppu->dot >= 1 && ppu->dot <= 256) {
        ppu__fetch_tile_data(ppu, 1);
        if (ppu->dot == 256) {
            ppu__inc_vert(ppu);
        }
    } else if (ppu->dot >= 257 && ppu->dot <= 320) {
        if (ppu->dot == 257) {
            // https://www.nesdev.org/wiki/PPU_scrolling#At_dot_257_of_each_scanline

            // Copy coarse-X
            ppu->v = copy_bits(ppu->v, ppu->t, 0x0, 0x4);
            // Copy nametable-X
            ppu->v = copy_bits(ppu->v, ppu->t, 0xA, 0xA);
        }

        // TODO: Fetch next scanline sprites
    } else if (ppu->dot >= 321 && ppu->dot <= 336) {
        ppu__fetch_tile_data(ppu, 321);
    } else if (ppu->dot >= 337 && ppu->dot <= 340) {
        b8 odd = ((ppu->dot - 337) & 0x1) == 0;
        if (odd) {
            // Load nametable address onto address bus
            ppu->address_bus = 0x2000 | (ppu->v & 0x0FFF);
        } else {
            ppu->bus.read(&ppu->bus, ppu->address_bus);
        }
    }
    // TODO: Fetch tiles for next scanline on the next dots.
}

static void ppu__background_step(Ppu* ppu) {
    // Pre-render line
    if (ppu->scanline == -1) {
        if (ppu->dot >= 280 && ppu->dot <= 304) {
            // FEDCBA98 76543210
            // 0YYYnnyy yyyxxxxx

            // Copy coarse-Y
            ppu->v = copy_bits(ppu->v, ppu->t, 0x5, 0x9);
            // Copy nametable-Y + fine-Y
            ppu->v = copy_bits(ppu->v, ppu->t, 0xB, 0xE);
        }
        ppu__scanline(ppu);
        // TODO: Skip last dot on odd frames
    }
    // Visible lines
    else if (ppu->scanline >= 0 && ppu->scanline < 240) {
        ppu__scanline(ppu);
    }
    // Post render line (idle)
    else if (ppu->scanline == 240) {}
    // V-Blank lines 
    else if (ppu->scanline >= 241) {}
}

static b8 is_sprite_on_scanline(const Ppu* ppu, SpriteOam sprite, i32 scanline) {
    i32 min = (i32) sprite.y;
    i32 max = (i32) sprite.y + (ppu->sprite_size == SPRITE_SIZE_8X16 ? 16 : 8);
    return scanline >= min && scanline < max;
}

static void ppu__sprite_step(Ppu* ppu) {
    assert(ppu->sprite_size == SPRITE_SIZE_8X8);

    // Not on visible scanline
    if (!(ppu->scanline >= -1 && ppu->scanline <= 240)) {
        return;
    }

    // https://www.nesdev.org/wiki/PPU_sprite_evaluation
    if (ppu->dot >= 1 && ppu->dot <= 64) {
        u8 index = ppu->dot-1;
        // Write on odd dots
        if ((index & 0x1) == 1) {
            index /= 2;
            u8* secondary_oam_memory = (u8*) &ppu->secondary_oam;
            secondary_oam_memory[index] = 0xFF;
        }

        ppu->secondary_oam_index = 0;
        ppu->primary_oam_index = 0;
    } else if (ppu->dot >= 65 && ppu->dot <= 256) {
        // TODO: Temporary solution
        if (ppu->primary_oam_index >= 32 || ppu->secondary_oam_index >= 8) {
            return;
        }

        b8 is_odd = (ppu->dot & 0x1) == 1;
        // Odd: Read from primary
        if (is_odd) {
            // Copying sprite
            if (ppu->copy_index == 0) {
                ppu->oam_data_latch = ppu->primary_oam[ppu->primary_oam_index];
                ppu->primary_oam_index++;
                // Don't know if this copy is actually necessary but better safe
                // than sorry.
                ppu->secondary_oam[ppu->secondary_oam_index].y = ppu->oam_data_latch.y;
            }
        }
        // Even: Write to secondary
        else {
            // A read should always have happened before this
            assert(ppu->primary_oam_index > 0);

            // Check if we're on the next scanline
            if (ppu->copy_index == 0 && is_sprite_on_scanline(ppu, ppu->oam_data_latch, ppu->scanline+1)) {
                // log_debug("Copy primary %d into secondary %d", ppu->primary_oam_index-1, ppu->secondary_oam_index);
                ppu->copy_index = 1;
            } else if (ppu->copy_index > 0) {
                // I'm truly sorry to anyone reading this.
                u8 byte = ((u8*) &ppu->oam_data_latch)[ppu->copy_index];
                u8* secondary_oam_mem = (u8*) &ppu->secondary_oam[ppu->secondary_oam_index];
                secondary_oam_mem[ppu->copy_index] = byte;
                ppu->copy_index++;
                if (ppu->copy_index == 4) {
                    // log_debug("%d:%d: %d, %d", ppu->scanline, ppu->dot, ppu->primary_oam_index-1, ppu->secondary_oam_index);
                    // log_debug("%d, %d", ppu->oam_data_latch.y, ppu->secondary_oam[ppu->secondary_oam_index].y);
                    ppu->copy_index = 0;
                    ppu->secondary_oam_index++;
                }
            }
        }
    } else if (ppu->dot >= 257 && ppu->dot <= 320) {
        if (ppu->dot == 257) {
            memcpy(ppu->to_render_oam,
                    ppu->secondary_oam,
                    ppu->secondary_oam_index*sizeof(SpriteOam));
            ppu->to_render_count = ppu->secondary_oam_index;

            ppu->secondary_oam_index = 0;
            ppu->primary_oam_index = 0;
            assert(ppu->copy_index == 0);
        }
    }
}

static inline b8 ppu__rendering_disabled(const Ppu* ppu) {
    return !ppu->mask.background && !ppu->mask.sprite;
}

PpuDot ppu_step(Ppu* ppu) {
    PpuDot result = {0};

    if (ppu->dot > 340) {
        ppu->dot = 0;
        ppu->scanline++;
        if (ppu->scanline > 260) {
            ppu->scanline = -1;
        }
    }

    if (ppu->ppu_address_delay == 0) {
        ppu->ppu_address_delay = -1;
        ppu->v = ppu->t;
    }
    ppu->ppu_address_delay = max(-1, ppu->ppu_address_delay-1);

    if (ppu->scanline == -1 && ppu->dot == 1) {
        ppu->vblank_flag = 0;
        ppu->vblank_nmi_signal = 0;
    } else if (ppu->scanline == 241 && ppu->dot == 1) {
        ppu->vblank_flag = 1;
        ppu->vblank_nmi_signal = ppu->vblank_nmi_enabled;
    }

    if (!ppu__rendering_disabled(ppu)) {
        ppu__background_step(ppu);
        ppu__sprite_step(ppu);

        if (ppu->scanline >= 0 &&
                ppu->scanline < 240 &&
                ppu->dot >= 1 && ppu->dot <= 256) {
            i32 x = ppu->dot-1;
            u8 sprite_color = {0};
            u8 sprite_priority = 0;
            u8 sprite_palette_entry = 0;
            for (u32 i = 0; i < ppu->to_render_count; i++) {
                // Reverse index for reverse painters ordering
                SpriteOam sprite = ppu->to_render_oam[i];

                assert(is_sprite_on_scanline(ppu, sprite, ppu->scanline));
                // log_debug("(%d, %d): (%d, %d)", x, ppu->scanline, sprite.x, sprite.y);
                if (x >= sprite.x && x < sprite.x+8) {
                    u32 sprite_x = x - sprite.x;
                    i32 sprite_y = ppu->scanline - sprite.y;

                    u16 pattern_addr_base = ppu->sprite_pattern_table_address;
                    pattern_addr_base |= sprite.tile_index << 4;
                    pattern_addr_base |= sprite_y;

                    // Flip horizontally
                    u8 plane_x = get_bit(sprite.attrib, 6) == 0 ? 7-sprite_x : sprite_x;

                    u8 low_plane = ppu->bus.read(&ppu->bus, pattern_addr_base);
                    u8 high_plane = ppu->bus.read(&ppu->bus, pattern_addr_base^0x8);
                    sprite_palette_entry = get_bit(low_plane, plane_x) |
                        (get_bit(high_plane, plane_x) << 1);
                    sprite_color = sprite_palette_entry + (sprite.attrib & 0x3)*4;
                    assert(sprite_color <= 0xF);
                    sprite_color ^= 0x10;
                    sprite_color = *ppu_get_color_ptr(ppu, sprite_color);

                    sprite_priority = get_bit(sprite.attrib, 5);

                    break;
                }
            }

            u8 tile_color = ppu->last_shifted;

            Color color = {255, 0, 255};
            b8 tile_opaque = (ppu->last_shifted_palette_entry & 0x3) != 0;
            b8 sprite_opaque = (sprite_palette_entry & 0x3) != 0;
            if (!tile_opaque && !sprite_opaque) {
                color = ppu_decode_color(ppu, *ppu_get_bg_color_ptr(ppu));
            } else if (!tile_opaque && sprite_opaque) {
                color = ppu_decode_color(ppu, sprite_color);
            } else if (tile_opaque && !sprite_opaque) {
                color = ppu_decode_color(ppu, tile_color);
            } else {
                if (sprite_priority == 0) {
                    // log_debug("Here");
                    color = ppu_decode_color(ppu, sprite_color);
                } else {
                    color = ppu_decode_color(ppu, tile_color);
                }
            }

            result = (PpuDot) {
                .visible = true,
                .color = color,
                .x = x,
                .y = ppu->scanline,
            };
        }
    } else {
        if (ppu->scanline >= 0 &&
                ppu->scanline < 240 &&
                ppu->dot >= 1 && ppu->dot <= 256) {
            result = (PpuDot) {
                .visible = true,
                .color = ppu_decode_color(ppu, *ppu_get_bg_color_ptr(ppu)),
                .x = ppu->dot-1,
                .y = ppu->scanline,
            };
        }
    }

    ppu->dot++;

    return result;
}

