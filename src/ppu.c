void ppu_scroll(Ppu* ppu, u8 value) {
    u16 fine = value & 7;
    u16 coarse = value >> 3;
    if (ppu->w == 0) {
        // Clear first 5 bits (coarse-X)
        ppu->t &= ~0x1F;
        ppu->t |= coarse;

        ppu->fine_x = fine;
    } else {
        // Bitmask 01110011 11100000 = 0x73E0
        ppu->t &= ~0x73E0;

        ppu->t |= coarse << 5;
        ppu->t |= fine << 12;
    }

    ppu->w = !ppu->w;
}

void ppu_address(Ppu* ppu, u8 value) {
    if (ppu->w == 0) {
        // Clear high bits
        ppu->t &= 0x00FF;
        ppu->t |= ((u16) value & 0x3F) << 8;
    } else {
        ppu->t &= 0xFF00;
        ppu->t |= value;
        ppu->ppu_address_delay = 1;
    }

    ppu->w = !ppu->w;
}

u8 ppu_data_read(Ppu* ppu) {
    u8 prev_read = ppu->read_data_latch;
    ppu->read_data_latch = ppu->bus.read(&ppu->bus, ppu->v);
    switch (ppu->vram_increment) {
        case VRAM_INCREMENT_ACROSS:
            ppu->v++;
            break;
        case VRAM_INCREMENT_DOWN:
            ppu->v += 32;
            break;
        default:
            UNREACHABLE();
    }
    ppu->v &= 0x7FFF;
    return prev_read;
}

void ppu_data_write(Ppu* ppu, u8 value) {
    ppu->bus.write(&ppu->bus, ppu->v, value);
    switch (ppu->vram_increment) {
        case VRAM_INCREMENT_ACROSS:
            ppu->v++;
            break;
        case VRAM_INCREMENT_DOWN:
            ppu->v += 32;
            break;
        default:
            UNREACHABLE();
    }
    ppu->v &= 0x7FFF;
}

