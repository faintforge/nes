Color ppu_decode_color(const Ppu* ppu, u8 color) {
    assert(color < 64);

    if (ppu->mask.grayscale) {
        color &= 0x30;
    }

    Color result = {0};
    if (ppu->palette_has_emph) {
        u8 emph_offset = ppu->mask.emph_red |
            ppu->mask.emph_green << 1 |
            ppu->mask.emph_blue << 2;
        result = ppu->palette[color + 64*emph_offset];
    } else {
        result = ppu->palette[color];
        const f32 emph_strength = 0.75f;

        u8 emph_value = ppu->mask.emph_red |
            ppu->mask.emph_green << 1 |
            ppu->mask.emph_blue << 2;

        // emph red + emph blue => darken green

        // emph red => darken blue + green
        // emph green => darken red + blue
        // emph red + green => darken blue

        // 000 => 000
        // 001 => 110
        // 011 => 100
        // 101 => 010
        // 111 => 111
        if (emph_value != 0 && emph_value != 7) {
            emph_value = ~emph_value;
        }

        if (get_bit(emph_value, 0)) { result.r *= emph_strength; }
        if (get_bit(emph_value, 1)) { result.g *= emph_strength; }
        if (get_bit(emph_value, 2)) { result.b *= emph_strength; }
    }

    return result;
}

u8* ppu_get_color_ptr(Ppu* ppu, u8 index) {
    assert(index < 0x20);
    // Sprite color 0 mirrors background color 0 in every palette
    b8 is_sprite = (index & 0x10) != 0;
    if (is_sprite && (index & 0x3) == 0) {
        index -= 0x10;
        // log_debug("Here");
    }
    return &ppu->palette_indices[index];
}

u8* ppu_get_bg_color_ptr(Ppu* ppu) {
    // Normal EXT pin
    u8 index = 0;
    if (ppu->v >= 0x3F00 && ppu->v < 0x4000) {
        index = (ppu->v) & 0x1F;
    }
    return ppu_get_color_ptr(ppu, index);
}

void ppu_ctrl(Ppu* ppu, u8 value) {
    // [Reference](https://www.nesdev.org/wiki/PPU_registers#PPUCTRL)
    // Bitmask 00001100_00000000 = 0x0C00
    ppu->t &= ~0x0C00;
    ppu->t |= (value & 3) << 10;

    // TODO: Writes to this register should be ignored until pre-render of the
    // second frame.

    ppu->vram_increment = get_bit(value, 2);
    ppu->sprite_pattern_table_address = 0x1000 * get_bit(value, 3);
    ppu->background_pattern_address = 0x1000 * get_bit(value, 4);
    ppu->sprite_size = get_bit(value, 5);
    if (get_bit(value, 6)) {
        fprintf(stderr, "ERR: %s master/slave select bit set!", __func__);
        UNREACHABLE();
    }
    ppu->vblank_nmi_enabled = get_bit(value, 7);
}

void ppu_mask(Ppu* ppu, u8 value) {
    ppu->mask = *(PpuMask*) &value;
}

u8 ppu_status(Ppu* ppu) {
    ppu->io_bus |= ppu->sprite_overflow_flag << 5;
    ppu->io_bus |= ppu->sprite0_hit_flag << 6;
    ppu->io_bus |= ppu->vblank_flag << 7;

    ppu->w = 0;
    ppu->vblank_flag = 0;

    return ppu->io_bus;
}

